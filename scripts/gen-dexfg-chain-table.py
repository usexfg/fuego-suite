#!/usr/bin/env python3
"""Regenerate the generated block of docs/dexfg/DEXFG_SWAP_CHAINS.md.

The block between the catalog-table markers is derived from
src/SwapDaemon/SwapPairCatalog.h (ids, support, family, chain id) and
src/SwapDaemon/AssetCatalog.cpp (which settlement assets have a feed id).

    python3 scripts/gen-dexfg-chain-table.py          # rewrite the doc
    python3 scripts/gen-dexfg-chain-table.py --check  # exit 1 if it drifted
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "src/SwapDaemon/SwapPairCatalog.h"
ASSETS = ROOT / "src/SwapDaemon/AssetCatalog.cpp"
DOC = ROOT / "docs/dexfg/DEXFG_SWAP_CHAINS.md"
BEGIN = "<!-- catalog-table:begin (generated by scripts/gen-dexfg-chain-table.py) -->"
END = "<!-- catalog-table:end -->"

CATALOG_ROW = re.compile(
    r'^\s*X\(\s*([A-Z_0-9]+)\s*,\s*(\d+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,'
    r'\s*([A-Z0-9_]+)\s*,\s*(\d+)\s*,\s*\d+\s*,\s*\d+\s*,\s*\d+\s*,\s*([A-Z_]+)\s*,',
    re.MULTILINE)
ASSET_ROW = re.compile(r'\{"([A-Z0-9]+)",\s*"([^"]*)",\s*"[^"]*",\s*"[^"]*",\s*"[^"]*"\}')

SUPPORT_ORDER = ("ACTIVE", "ADAPTER", "GATED", "STAGED")


def read_pairs():
    pairs = []
    for name, pid, key, asset, _display, family, chain_id, support in CATALOG_ROW.findall(CATALOG.read_text()):
        pairs.append({"id": int(pid), "name": name, "key": key, "asset": asset,
                      "family": family, "chain_id": int(chain_id), "support": support})
    ids = [p["id"] for p in pairs]
    if ids != list(range(len(ids))):
        sys.exit("catalog ids are not contiguous from 0")
    return pairs


def priced_assets():
    return {asset for asset, feed in ASSET_ROW.findall(ASSETS.read_text()) if feed}


def start_verdict(pair, priced):
    if pair["support"] == "STAGED":
        return "No — STAGED"
    if pair["support"] == "GATED":
        return "No — transport awaits its end-to-end gate"
    if pair["asset"] not in priced:
        return "No — no verified price feed"
    if pair["family"] == "SOLANA":
        return "Yes — local RPC + deployed program"
    if pair["family"] == "EVM":
        return "Yes — signer + HashedTimelock on this chain"
    return "Yes — configured client"


def render(pairs, priced):
    counts = {s: sum(1 for p in pairs if p["support"] == s) for s in SUPPORT_ORDER}
    verdicts = [(p, start_verdict(p, priced)) for p in pairs]
    startable = [p for p, v in verdicts if v.startswith("Yes")]

    def names(predicate):
        return ", ".join("%s (%d)" % (p["name"], p["id"]) for p, v in verdicts if predicate(p, v))

    lines = [BEGIN, "",
             "%d wire ids: %s." % (len(pairs), ", ".join("%d %s" % (counts[s], s) for s in SUPPORT_ORDER)),
             "**%d can start a swap once configured.**" % len(startable), "",
             "| Gate that blocks | Pairs |", "|---|---|",
             "| none (configure + deploy) | %s |" % names(lambda p, v: v.startswith("Yes")),
             "| price feed | %s |" % (names(lambda p, v: v.endswith("price feed")) or "—"),
             "| end-to-end gate (GATED) | %s |" % (names(lambda p, v: p["support"] == "GATED") or "—"),
             "| STAGED | %s |" % (names(lambda p, v: p["support"] == "STAGED") or "—"), "",
             "| Id | Symbol | Config key | Settles in | Family | Chain id | Support | Can start a swap |",
             "|---:|---|---|---|---|---:|---|---|"]
    for p, verdict in verdicts:
        chain_id = str(p["chain_id"]) if p["chain_id"] else "—"
        lines.append("| %d | %s | `%s` | %s | %s | %s | %s | %s |" % (
            p["id"], p["name"], p["key"], p["asset"], p["family"], chain_id, p["support"], verdict))
    lines += ["", END]
    return "\n".join(lines)


def main():
    doc = DOC.read_text()
    if BEGIN not in doc or END not in doc:
        sys.exit("%s lacks the catalog-table markers" % DOC)
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    updated = head + render(read_pairs(), priced_assets()) + tail
    if "--check" in sys.argv[1:]:
        if updated != doc:
            sys.exit("docs/dexfg/DEXFG_SWAP_CHAINS.md is stale; run scripts/gen-dexfg-chain-table.py")
        return
    DOC.write_text(updated)


if __name__ == "__main__":
    main()
